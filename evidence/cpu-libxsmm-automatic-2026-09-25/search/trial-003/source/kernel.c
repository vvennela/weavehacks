void gemm(int n, const float *A, const float *B, float *C) {
    if (n != 512) {
        fallback_gemm(n, A, B, C);
        return;
    }
    /* Row-major C=A*B is column-major C^T=B^T*A^T. Argument offsets
       are exported from the pinned LIBXSMM ABI; all other fields are zero. */
    const void *parameters[22] = {0};
    parameters[4] = B;
    parameters[10] = A;
    parameters[16] = C;
    sera_libxsmm_512(parameters);
}

